import { readFile, writeFile } from 'node:fs/promises';

export async function generateHostBindings() {
  const sdk = new URL('../', import.meta.url);
  const interfaces = ['ui', 'events', 'http', 'launch', 'log', 'native', 'notify', 'pipes', 'secrets', 'storage', 'style', 'system', 'timers', 'websocket'];
  const lines = ['// Generated by scripts/host-bindings.mjs from jco declarations. Do not edit.', "import { fromWit } from './compat.ts';"];
  for (const name of interfaces) {
    lines.push(`import * as ${name}Import from 'mypaper:plugin/${name}@0.1.0';`);
    const declarations = await readFile(new URL(`src/generated/interfaces/mypaper-plugin-${name}.d.ts`, sdk), 'utf8');
    const methods = [...declarations.matchAll(/^export function (\w+)\(/gm)].map(match => match[1]);
    lines.push(`export const ${name === 'ui' ? 'witUi' : name} = {`);
    for (const method of methods) {
      lines.push(`  ${method}(...args: Parameters<typeof ${name}Import.${method}>) { return fromWit(${name}Import.${method}(...args)); },`);
    }
    lines.push('};');
  }
  await writeFile(new URL('src/host.ts', sdk), lines.join('\n') + '\n');
}
